CREATE TABLE IF NOT EXISTS ADMIN_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT ADMIN_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS ADMIN_SESSION_IX1 ON ADMIN_SESSION (SESSION_ID);
CREATE INDEX IF NOT EXISTS ADMIN_SESSION_IX2 ON ADMIN_SESSION (EXPIRY_TIME);
CREATE INDEX IF NOT EXISTS ADMIN_SESSION_IX3 ON ADMIN_SESSION (PRINCIPAL_NAME);
CREATE TABLE IF NOT EXISTS ADMIN_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    CONSTRAINT ADMIN_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT ADMIN_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES ADMIN_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
